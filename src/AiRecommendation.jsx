import React, {useEffect, useState} from 'react';
import {BrainCircuit, RotateCw} from 'lucide-react';
import {analyzeResource} from './analyze-resource.js';

const labels={
  tr:{title:'AI önerisi',fallbackTitle:'Veri analizi önerisi',loading:'Örnek veriler analiz ediliyor…',retry:'AI ile yeniden dene',source:'AI tarafından örnek verilerden üretildi',fallbackSource:'Örnek verilerden hesaplandı · AI modeline erişilemiyor'},
  en:{title:'AI recommendation',fallbackTitle:'Data analysis recommendation',loading:'Analyzing illustrative data…',retry:'Retry AI',source:'Generated by AI from illustrative data',fallbackSource:'Calculated from illustrative data · AI model unavailable'}
};

export default function AiRecommendation({resource,language}){
  const [result,setResult]=useState({status:'loading',text:''});
  const [attempt,setAttempt]=useState(0);
  useEffect(()=>{
    const controller=new AbortController();
    setResult({status:'loading',text:''});
    fetch(`/api/recommend?resource=${encodeURIComponent(resource)}&lang=${language}`,{signal:controller.signal})
      .then(response=>{if(!response.ok)throw new Error('recommendation_failed');return response.json()})
      .then(data=>{if(!controller.signal.aborted)setResult({status:'success',text:data.recommendation})})
      .catch(()=>{if(!controller.signal.aborted)setResult({status:'fallback',text:analyzeResource(resource,language)})});
    return()=>controller.abort();
  },[resource,language,attempt]);
  const t=labels[language]||labels.tr;
  return <div className="ai-note ai-live-note" aria-busy={result.status==='loading'}><span><BrainCircuit size={19}/></span><p><strong>{result.status==='fallback'?t.fallbackTitle:t.title}</strong><span role="status">{result.status==='loading'?t.loading:result.text}</span>{result.status!=='loading'&&<small>{result.status==='success'?t.source:t.fallbackSource}</small>}</p>{result.status==='fallback'&&<button type="button" onClick={()=>setAttempt(value=>value+1)} aria-label={t.retry} title={t.retry}><RotateCw size={15}/></button>}</div>;
}
